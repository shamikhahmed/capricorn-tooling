#!/usr/bin/env node
/**
 * build-design-tokens.mjs — Cap Foundation (FND-01)
 * Reads shared/design/tokens.json → generates CSS / Tailwind / Dart / TS stubs.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const DESIGN = join(ROOT, 'shared', 'design');
const tokens = JSON.parse(readFileSync(join(DESIGN, 'tokens.json'), 'utf8'));

mkdirSync(DESIGN, { recursive: true });

function cssVars(obj, prefix = '') {
  return Object.entries(obj)
    .map(([k, v]) => `  --${prefix}${k}: ${v};`)
    .join('\n');
}

function buildFoundationCss() {
  const light = tokens.themes.light;
  const dark = tokens.themes.dark;
  const typeBlocks = Object.entries(tokens.type)
    .map(([name, t]) => {
      return `  --type-${name}-size: ${t.size};\n  --type-${name}-lh: ${t.lineHeight};\n  --type-${name}-weight: ${t.weight};`;
    })
    .join('\n');

  return `/* GENERATED by scripts/build-design-tokens.mjs — DO NOT EDIT. */\n:root {\n${cssVars(tokens.spacing)}\n${cssVars(tokens.radius)}\n${typeBlocks}\n${cssVars(tokens.fonts)}\n${cssVars(tokens.elevation)}\n${Object.entries(tokens.zIndex).map(([k, v]) => `  --${k}: ${v};`).join('\n')}\n${cssVars(tokens.motion)}\n${cssVars(light)}\n}\n\n@media (prefers-color-scheme: dark) {\n:root {\n${cssVars(dark)}\n}\n}\n\n[data-theme="light"] {\n${cssVars(light)}\n}\n\n[data-theme="dark"] {\n${cssVars(dark)}\n}\n\n@supports (font: -apple-system-body) {\n  html { font: -apple-system-body; }\n}\n\nbody {\n  margin: 0;\n  font-family: var(--font-ui);\n  font-size: var(--type-body-size);\n  line-height: var(--type-body-lh);\n  color: var(--text);\n  background: var(--bg);\n}\n\n:focus-visible {\n  outline: 2px solid var(--focus);\n  outline-offset: 2px;\n}\n\n@media (prefers-reduced-motion: reduce) {\n  *, *::before, *::after {\n    animation-duration: 0.01ms !important;\n    animation-iteration-count: 1 !important;\n    transition-duration: 120ms !important;\n    scroll-behavior: auto !important;\n  }\n}\n`;
}

function buildTailwindTheme() {
  const light = tokens.themes.light;
  const colorLines = Object.entries(light)
    .map(([k, v]) => `  --color-${k}: ${v};`)
    .join('\n');
  return `/* GENERATED by scripts/build-design-tokens.mjs — DO NOT EDIT. */\n@theme {\n${colorLines}\n}\n`;
}

function buildTokensTs() {
  return `/* GENERATED by scripts/build-design-tokens.mjs — DO NOT EDIT. */\nexport const capTokens = ${JSON.stringify(tokens, null, 2)} as const;\nexport type CapTheme = keyof typeof capTokens.themes;\n`;
}

function buildDart() {
  const light = tokens.themes.light;
  const fields = Object.keys(light)
    .map((k) => {
      const name = k.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
      return `  final Color ${name};`;
    })
    .join('\n');
  const ctor = Object.keys(light)
    .map((k) => {
      const name = k.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
      return `    required this.${name},`;
    })
    .join('\n');
  const lightVals = Object.entries(light)
    .map(([k, v]) => {
      const name = k.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
      if (String(v).startsWith('#') && v.length === 7) {
        return `    ${name}: Color(0xFF${v.slice(1).toUpperCase()}),`;
      }
      return `    ${name}: const Color(0xFF000000), // non-hex: ${v}`;
    })
    .join('\n');
  return `// GENERATED by scripts/build-design-tokens.mjs — DO NOT EDIT.\nimport 'package:flutter/material.dart';\n\n@immutable\nclass CapTokens extends ThemeExtension<CapTokens> {\n${fields}\n\n  const CapTokens({\n${ctor}\n  });\n\n  static const light = CapTokens(\n${lightVals}\n  );\n\n  @override\n  CapTokens copyWith({Color? accent}) => this;\n\n  @override\n  CapTokens lerp(ThemeExtension<CapTokens>? other, double t) => this;\n}\n`;
}

writeFileSync(join(DESIGN, 'cap-foundation.css'), buildFoundationCss());
writeFileSync(join(DESIGN, 'tailwind-theme.css'), buildTailwindTheme());
writeFileSync(join(DESIGN, 'tokens.ts'), buildTokensTs());
writeFileSync(join(DESIGN, 'cap_tokens.dart'), buildDart());
console.log('Wrote Cap Foundation outputs to shared/design/');
